CREATE TABLE IF NOT EXISTS tx (
  id TEXT PRIMARY KEY,
  date TEXT NOT NULL,
  time TEXT NOT NULL,
  type TEXT NOT NULL,
  subtype TEXT NOT NULL DEFAULT '',
  total INTEGER NOT NULL DEFAULT 0,
  amount INTEGER NOT NULL DEFAULT 0,
  rand INTEGER NOT NULL DEFAULT 0,
  balance INTEGER,
  account TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT '',
  raw TEXT NOT NULL DEFAULT '',
  sort_at TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS review (id TEXT PRIMARY KEY, raw TEXT NOT NULL, received TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS budgets (category TEXT PRIMARY KEY, amount INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rules (id INTEGER PRIMARY KEY AUTOINCREMENT, keyword TEXT NOT NULL, category TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS accounts (last4 TEXT PRIMARY KEY, name TEXT NOT NULL);
